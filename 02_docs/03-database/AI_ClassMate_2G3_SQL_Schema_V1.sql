-- AI ClassMate 2G3 — PostgreSQL SQL Schema V1.0
-- File: AI_ClassMate_2G3_SQL_Schema_V1.sql
-- Date: 2026-10-10
-- Purpose: Initial schema for MVP, based on Database Design V1.0.
--
-- IMPORTANT:
-- 1. This script creates structure only; it does not import real student data.
-- 2. Unconfirmed behavior criteria must remain PENDING_CONFIRMATION and must not
--    be used for official scoring.
-- 3. Blank/unknown values are represented by NULL, not silently converted to 0.
-- 4. Run against a dedicated development database first, not production.

BEGIN;

CREATE TABLE IF NOT EXISTS classes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_code      VARCHAR(30) NOT NULL UNIQUE,
    class_name      VARCHAR(100) NOT NULL,
    school_year     VARCHAR(20) NOT NULL,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS teachers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name    VARCHAR(120) NOT NULL,
    email           VARCHAR(255) UNIQUE,
    role            VARCHAR(30) NOT NULL DEFAULT 'TEACHER'
                    CHECK (role IN ('TEACHER', 'ADMIN')),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS students (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id        BIGINT NOT NULL REFERENCES classes(id) ON DELETE RESTRICT,
    student_code    VARCHAR(30) NOT NULL,
    display_name    VARCHAR(120),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_students_class_code UNIQUE (class_id, student_code)
);

CREATE TABLE IF NOT EXISTS behavior_criteria (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    criterion_code  VARCHAR(40) NOT NULL UNIQUE,
    criterion_name  VARCHAR(150) NOT NULL,
    category        VARCHAR(20) NOT NULL
                    CHECK (category IN ('POSITIVE', 'NEGATIVE')),
    points           INTEGER,
    rule_status     VARCHAR(30) NOT NULL DEFAULT 'PENDING_CONFIRMATION'
                    CHECK (rule_status IN (
                        'PENDING_CONFIRMATION', 'CONFIRMED', 'REJECTED', 'INACTIVE'
                    )),
    description     TEXT,
    effective_from  DATE,
    effective_to    DATE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_behavior_criteria_effective_dates
        CHECK (effective_to IS NULL OR effective_from IS NULL OR effective_to >= effective_from),
    CONSTRAINT ck_confirmed_criteria_has_points
        CHECK (rule_status <> 'CONFIRMED' OR points IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS behavior_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      BIGINT NOT NULL REFERENCES students(id) ON DELETE RESTRICT,
    class_id        BIGINT NOT NULL REFERENCES classes(id) ON DELETE RESTRICT,
    occurred_at     TIMESTAMPTZ NOT NULL,
    description     TEXT,
    source          VARCHAR(30) NOT NULL DEFAULT 'MANUAL'
                    CHECK (source IN ('MANUAL', 'IMPORT', 'SYSTEM')),
    status          VARCHAR(30) NOT NULL DEFAULT 'DRAFT'
                    CHECK (status IN (
                        'DRAFT', 'PENDING_REVIEW', 'CONFIRMED', 'REJECTED', 'VOIDED'
                    )),
    entered_by      BIGINT REFERENCES teachers(id) ON DELETE RESTRICT,
    reviewed_by     BIGINT REFERENCES teachers(id) ON DELETE RESTRICT,
    reviewed_at     TIMESTAMPTZ,
    review_note     TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_event_review_fields
        CHECK (
            (reviewed_by IS NULL AND reviewed_at IS NULL)
            OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
        )
);

CREATE TABLE IF NOT EXISTS behavior_event_items (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id            BIGINT NOT NULL REFERENCES behavior_events(id) ON DELETE RESTRICT,
    criterion_id        BIGINT NOT NULL REFERENCES behavior_criteria(id) ON DELETE RESTRICT,
    points_applied      INTEGER,
    points_status       VARCHAR(30) NOT NULL DEFAULT 'PENDING_CONFIRMATION'
                        CHECK (points_status IN (
                            'PENDING_CONFIRMATION', 'CONFIRMED', 'NEEDS_REVIEW'
                        )),
    duplicate_of_item_id BIGINT REFERENCES behavior_event_items(id) ON DELETE RESTRICT,
    note                TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_confirmed_item_has_points
        CHECK (points_status <> 'CONFIRMED' OR points_applied IS NOT NULL),
    CONSTRAINT ck_item_not_duplicate_of_self
        CHECK (duplicate_of_item_id IS NULL OR duplicate_of_item_id <> id)
);

CREATE TABLE IF NOT EXISTS monthly_summaries (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          BIGINT NOT NULL REFERENCES students(id) ON DELETE RESTRICT,
    class_id            BIGINT NOT NULL REFERENCES classes(id) ON DELETE RESTRICT,
    summary_year        SMALLINT NOT NULL CHECK (summary_year BETWEEN 2000 AND 2200),
    summary_month       SMALLINT NOT NULL CHECK (summary_month BETWEEN 1 AND 12),
    positive_points     INTEGER,
    negative_points     INTEGER,
    total_points        INTEGER,
    gift_count          INTEGER,
    remainder_points    INTEGER,
    data_status         VARCHAR(30) NOT NULL DEFAULT 'NEEDS_REVIEW'
                        CHECK (data_status IN (
                            'NEEDS_REVIEW', 'READY', 'APPROVED', 'REOPENED', 'DRAFT'
                        )),
    rule_version        VARCHAR(30) NOT NULL DEFAULT '1.0',
    calculated_at       TIMESTAMPTZ,
    approved_by         BIGINT REFERENCES teachers(id) ON DELETE RESTRICT,
    approved_at         TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_monthly_summary_student_month
        UNIQUE (student_id, summary_year, summary_month),
    CONSTRAINT ck_summary_gift_count_nonnegative
        CHECK (gift_count IS NULL OR gift_count >= 0),
    CONSTRAINT ck_summary_remainder_nonnegative
        CHECK (remainder_points IS NULL OR remainder_points >= 0),
    CONSTRAINT ck_summary_approval_fields
        CHECK (
            (approved_by IS NULL AND approved_at IS NULL)
            OR (approved_by IS NOT NULL AND approved_at IS NOT NULL)
        ),
    CONSTRAINT ck_negative_total_no_gifts_or_remainder
        CHECK (
            total_points IS NULL
            OR total_points >= 0
            OR (gift_count = 0 AND remainder_points IS NULL)
        )
);

CREATE TABLE IF NOT EXISTS student_comments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          BIGINT NOT NULL REFERENCES students(id) ON DELETE RESTRICT,
    class_id            BIGINT NOT NULL REFERENCES classes(id) ON DELETE RESTRICT,
    summary_year        SMALLINT NOT NULL CHECK (summary_year BETWEEN 2000 AND 2200),
    summary_month       SMALLINT NOT NULL CHECK (summary_month BETWEEN 1 AND 12),
    content             TEXT NOT NULL,
    source_type         VARCHAR(20) NOT NULL
                        CHECK (source_type IN ('TEACHER', 'AI_DRAFT')),
    status              VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
                        CHECK (status IN ('DRAFT', 'APPROVED', 'REJECTED')),
    generated_by_model  VARCHAR(100),
    approved_by         BIGINT REFERENCES teachers(id) ON DELETE RESTRICT,
    approved_at         TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_comment_approval_fields
        CHECK (
            (approved_by IS NULL AND approved_at IS NULL)
            OR (approved_by IS NOT NULL AND approved_at IS NOT NULL)
        ),
    CONSTRAINT ck_ai_comment_must_start_as_draft_or_rejected
        CHECK (source_type <> 'AI_DRAFT' OR status IN ('DRAFT', 'REJECTED', 'APPROVED'))
);

CREATE TABLE IF NOT EXISTS review_issues (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          BIGINT REFERENCES students(id) ON DELETE RESTRICT,
    event_id            BIGINT REFERENCES behavior_events(id) ON DELETE RESTRICT,
    summary_id          BIGINT REFERENCES monthly_summaries(id) ON DELETE RESTRICT,
    issue_code          VARCHAR(50) NOT NULL,
    severity            VARCHAR(20) NOT NULL
                        CHECK (severity IN ('INFO', 'WARNING', 'BLOCKING')),
    message             TEXT NOT NULL,
    status              VARCHAR(20) NOT NULL DEFAULT 'OPEN'
                        CHECK (status IN ('OPEN', 'RESOLVED', 'DISMISSED')),
    resolved_by         BIGINT REFERENCES teachers(id) ON DELETE RESTRICT,
    resolved_at         TIMESTAMPTZ,
    resolution_note     TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_review_issue_resolution_fields
        CHECK (
            (status = 'OPEN' AND resolved_at IS NULL)
            OR (status <> 'OPEN')
        )
);

CREATE TABLE IF NOT EXISTS audit_logs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id        BIGINT REFERENCES teachers(id) ON DELETE RESTRICT,
    entity_type     VARCHAR(50) NOT NULL,
    entity_id       BIGINT NOT NULL,
    action          VARCHAR(30) NOT NULL
                    CHECK (action IN ('CREATE', 'UPDATE', 'CONFIRM', 'REJECT', 'APPROVE', 'REOPEN', 'VOID')),
    before_data     JSONB,
    after_data      JSONB,
    reason          TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Indexes for common lookups and monthly calculations.
CREATE INDEX IF NOT EXISTS idx_students_class_active
    ON students (class_id, is_active);

CREATE INDEX IF NOT EXISTS idx_behavior_criteria_status
    ON behavior_criteria (rule_status, category);

CREATE INDEX IF NOT EXISTS idx_behavior_events_student_time
    ON behavior_events (student_id, occurred_at DESC);

CREATE INDEX IF NOT EXISTS idx_behavior_events_class_status_time
    ON behavior_events (class_id, status, occurred_at);

CREATE INDEX IF NOT EXISTS idx_behavior_event_items_event
    ON behavior_event_items (event_id);

CREATE INDEX IF NOT EXISTS idx_behavior_event_items_criterion_status
    ON behavior_event_items (criterion_id, points_status);

CREATE INDEX IF NOT EXISTS idx_monthly_summaries_class_month
    ON monthly_summaries (class_id, summary_year, summary_month);

CREATE INDEX IF NOT EXISTS idx_student_comments_student_month
    ON student_comments (student_id, summary_year, summary_month);

CREATE INDEX IF NOT EXISTS idx_review_issues_open_severity
    ON review_issues (status, severity, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_audit_logs_entity
    ON audit_logs (entity_type, entity_id, created_at DESC);

